package com.testtube.app.extractor;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertNull;

import org.junit.Test;
import org.schabi.newpipe.extractor.MediaFormat;
import org.schabi.newpipe.extractor.services.youtube.ItagItem;
import org.schabi.newpipe.extractor.stream.AudioStream;
import org.schabi.newpipe.extractor.stream.AudioTrackType;

import java.util.List;

public class PlaybackPlannerTest {

	private static AudioStream track(String id, AudioTrackType type, boolean autoDubbed, int bitrate)
					throws Exception {
		ItagItem itag = new ItagItem(ItagItem.getItag(140));
		itag.setAutoGenerated(autoDubbed);
		return new AudioStream.Builder()
						.setId(id)
						.setContent("https://example.com/" + id, true)
						.setMediaFormat(MediaFormat.M4A)
						.setAverageBitrate(bitrate)
						.setAudioTrackType(type)
						.setItagItem(itag)
						.build();
	}

	@Test
	public void originalTrackComesFirst() throws Exception {
		AudioStream aiDub = track("ai", AudioTrackType.DUBBED, true, 160);
		AudioStream dub = track("dub", AudioTrackType.DUBBED, false, 160);
		AudioStream described = track("desc", AudioTrackType.DESCRIPTIVE, false, 160);
		AudioStream original = track("orig", AudioTrackType.ORIGINAL, false, 128);
		List<AudioStream> sorted = PlaybackPlanner.originalFirst(List.of(aiDub, described, dub, original));
		assertEquals(List.of(original, dub, described, aiDub), sorted);
	}

	@Test
	public void untaggedTrackBeatsDubs() throws Exception {
		AudioStream aiDub = track("ai", null, true, 160);
		AudioStream untagged = track("plain", null, false, 128);
		assertEquals(untagged, PlaybackPlanner.originalAudio(List.of(aiDub, untagged)));
	}

	@Test
	public void betterBitrateWinsWithinTheSameKind() throws Exception {
		AudioStream low = track("low", AudioTrackType.ORIGINAL, false, 48);
		AudioStream high = track("high", AudioTrackType.ORIGINAL, false, 128);
		assertEquals(high, PlaybackPlanner.originalAudio(List.of(low, high)));
	}

	@Test
	public void noTracksMeansNoAudio() {
		assertNull(PlaybackPlanner.originalAudio(List.of()));
	}
}
